def _occurrence(case_id: str, attempt_id: str, status: SemanticStatus, synthetic=SyntheticKind.REAL):
    recomputed = HASH_1 if status is not SemanticStatus.NOT_RECOMPUTED else None
    return FindingOccurrence(
        source_id=SOURCE_ID,
        attempt_id=attempt_id,
        case_id=case_id,
        recompute_status=status,
        comparison_hash=HASH_2,
        original_exact_signature=HASH_1,
        fingerprint=FINGERPRINT,
        recomputed_comparison_hash=recomputed,
        synthetic=synthetic,
    )


def _build(assessment, **kwargs):
    defaults = dict(
        tool_name="mtsql-typecheck",
        writer_version="4.0.0",
        delivery_id=DELIVERY_ID,
        synthetic=SyntheticKind.REAL,
        findings=_zero_findings(),
        reviews=_empty_reviews(),
        files=_base_files(),
        reproduction_notes=("独立复现请使用 export 生成的 SQL 包",),
        generated_at=GENERATED_AT,
    )
    defaults.update(kwargs)
    return build_report(assessment=assessment, **defaults)


