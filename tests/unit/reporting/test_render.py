@pytest.mark.parametrize("doc_fn", ALL_DOCS, ids=lambda fn: fn.__name__)
def test_markdown_and_html_agree(doc_fn):
    doc = doc_fn()
    md = render_markdown(doc)
    html = render_html(doc)
    for occurrence in doc.occurrences:
        assert occurrence.occurrence_id in md
        assert occurrence.occurrence_id in html
    for dimension in (
        doc.header.structural,
        doc.header.semantic,
        doc.header.provenance,
        doc.header.execution_safety,
    ):
        assert dimension.status.value in md
        assert dimension.status.value in html
    for name, value in (
        ("真实候选", doc.findings.real_candidates),
        ("合成未知候选", doc.findings.unknown_synthetic_candidates),
        ("语义冲突", doc.findings.conflicts),
    ):
        assert name in md and name in html
        assert str(value) in md and str(value) in html


