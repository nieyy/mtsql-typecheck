def _dim(
    dimension: AssessmentDimension,
    status,
    *,
    applicable: bool = True,
    checked: int = 1,
    unchecked: int = 0,
    reason_codes: tuple[str, ...] = (),
    detail: str | None = None,
) -> DimensionResult:
    return DimensionResult(
        dimension=dimension,
        applicable=applicable,
        status=status,
        reason_codes=reason_codes,
        checked_objects=checked,
        unchecked_objects=unchecked,
        detail=detail,
    )


def _dims(
    structural=StructuralStatus.COMPLETE,
    semantic=SemanticStatus.RECOMPUTED,
    provenance=ProvenanceStatus.CORROBORATED,
    safety=ExecutionSafetyStatus.CONFIRMED,
    *,
    structural_kwargs=None,
    semantic_kwargs=None,
    provenance_kwargs=None,
    safety_kwargs=None,
):
    return (
        _dim(AssessmentDimension.STRUCTURAL, structural, **(structural_kwargs or {})),
        _dim(AssessmentDimension.SEMANTIC, semantic, **(semantic_kwargs or {})),
        _dim(AssessmentDimension.PROVENANCE, provenance, **(provenance_kwargs or {})),
        _dim(AssessmentDimension.EXECUTION_SAFETY, safety, **(safety_kwargs or {})),
    )


def _assessment(dims, *, native_kind=NativeKind.GENERATION, selection=None, attempts=()):
    structural, semantic, provenance, safety = dims
    return SourceAssessment(
        source_id=SOURCE_ID,
        native_kind=native_kind,
        structural=structural,
        semantic=semantic,
        provenance=provenance,
        execution_safety=safety,
        attempts=tuple(attempts),
        selection=selection,
        reason_codes=(),
    )


def _empty_reviews():
    from mtsql_typecheck.reporting.model import ReviewSet

    return ReviewSet(accepted=(), duplicates_ignored=(), historical=(), conflicts=(), has_conflict=False)


