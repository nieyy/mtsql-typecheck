def test_diff_summary_truncation_marker():
    doc = doc_longtext()
    detail = doc.case_details[0]
    assert "展示截断" in detail.diff_summary
    assert detail.diff_summary.endswith("……（展示截断：超过 100 行 / 1KiB 显示上限）")
    lines = detail.diff_summary.count("\n") + 1
    assert lines <= 101  # kept lines + at most one marker line
    assert len(detail.diff_summary.encode("utf-8")) <= 1024
    assert "行 0" in detail.diff_summary  # beginning is preserved, never silent
    md = render_markdown(doc)
    assert "展示截断" in md
    html = render_html(doc)
    assert "展示截断" in html


def test_diff_summary_line_cap_only():
    # 150 short lines hit the 100-line cap before the byte cap.
    text = "\n".join(f"line-{i}" for i in range(150))
    bounded = bound_diff_summary(text)
    assert bounded.count("\n") + 1 == 101
    assert bounded.endswith("……（展示截断：超过 100 行 / 1KiB 显示上限）")
    assert "line-0" in bounded and "line-149" not in bounded


def test_diff_summary_within_caps_unchanged():
    assert bound_diff_summary(None) is None
    assert bound_diff_summary("A: 2 行\nB: 3 行") == "A: 2 行\nB: 3 行"
    # Idempotent: re-bounding an already bounded summary adds no second marker.
    once = bound_diff_summary("x" * 2000)
    assert bound_diff_summary(once) == once


